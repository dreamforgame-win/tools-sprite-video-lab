  function promptTemplatesByCategory(categoryId) {
    return PROMPT_TEMPLATES.filter((template) => template.category === categoryId);
  }

  function promptTemplateById(templateId) {
    return PROMPT_TEMPLATES.find((template) => template.id === templateId) || null;
  }

  function promptTemplateCategoryForAssetType(assetType) {
    const mapping = {
      character: "character",
      scene: "scene",
      ui: "ui",
      icon: "icon",
      skill_icon: "icon",
      equipment: "icon",
      effect: "effect",
    };
    return mapping[String(assetType || "").toLowerCase()] || "";
  }

  return {
    PROMPT_TEMPLATE_CATEGORIES,
    PROMPT_TEMPLATES,
    promptTemplatesByCategory,
    promptTemplateById,
    promptTemplateCategoryForAssetType,
  };
